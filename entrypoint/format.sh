#!/bin/env bash
#
# Format every hand-written source tree: the C engine (clang-format) and the three
# engine ports under port/ -- Python (ruff), Rust (cargo fmt) and Haskell (ormolu).
# Every formatter runs, and the script fails if any of them failed (the status
# accumulates; no `set -e`, which would stop at the first failure).
#
# The port lint suites in meson (port-python-lint, port-rust-lint) only CHECK the
# formatting; this script applies it. `make check-format` runs it and then fails on
# any `git diff`.

[ -d /spimulator ] && cd /spimulator

status=0

# pgu/upstreamSource/ holds third-party sources kept byte-identical to
# upstream -- never reformat them (William Emerison Six <billsix@gmail.com>, 2026-07-29).
find . -path ./pgu/upstreamSource -prune -o \( -iname "*.c" -o -iname "*.cpp" -o -iname "*.h" -o -iname "*.hpp" \) -print0 | xargs -0 clang-format -i || status=1

# Python port: ruff's safe fixes (import order and the like), then the formatter.
# --exit-zero: lint findings that need a hand edit are port-python-lint's job, not
# a formatting failure.
(cd port/python && ruff check --fix --exit-zero --quiet . && ruff format --quiet .) || status=1

# Rust port: rustfmt, configured by port/rust/rustfmt.toml.
cargo fmt --manifest-path port/rust/Cargo.toml || status=1

# Haskell port: ormolu, which reads the language extensions from the .cabal file.
# Files tools/gen_opcodes.py writes (marked "GENERATED by tools/gen_opcodes.py") are
# skipped: the generator writes them in their final form, and the
# generated_opcode_tables test fails if a committed one differs from its output.
# The Python and Rust generated files already match ruff and rustfmt.
find port/haskell/src port/haskell/tools port/haskell/tests -name "*.hs" -print0 |
    xargs -0 grep -L --null "GENERATED by tools/gen_opcodes.py" |
    xargs -0 ormolu --mode inplace || status=1

exit $status
