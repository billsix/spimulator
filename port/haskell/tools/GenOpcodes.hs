-- | Generate @src/Opcodes.hs@ from the C engine's @include/opcodes.h@.
--
-- @opcodes.h@ is an X-macro list: one @OP(name, TOKEN, TYPE, encoding)@ row
-- per instruction, pseudo-instruction and directive.  The C engine includes
-- it several times to build several tables.  This program reads the same
-- rows and writes them out as Haskell: an 'Opcode' data type with one
-- constructor per row (named exactly like the C token, so a reader can grep
-- both sources for @TOK_ADD_OPCODE@) and a list of rows.
--
-- Run it from @port/haskell/@ after @opcodes.h@ changes:
--
-- > runghc tools/GenOpcodes.hs ../../include/opcodes.h > src/Opcodes.hs
module Main (main) where

import Data.Char (isSpace)
import Data.List (intercalate, isPrefixOf)
import System.Environment (getArgs)

-- | One OP(...) row: name, token, type tag, encoding text.
data Row = Row String String String String

main :: IO ()
main = do
  args <- getArgs
  path <- case args of
    [p] -> pure p
    _ -> fail "usage: runghc tools/GenOpcodes.hs include/opcodes.h"
  text <- readFile path
  putStr (render (rows (stripComments text)))

-- | Remove C comments, so that the @OP(@ examples in the file's header
-- comment are not taken for rows.
stripComments :: String -> String
stripComments ('/' : '*' : rest) = ' ' : stripComments (dropComment rest)
  where
    dropComment ('*' : '/' : more) = more
    dropComment (_ : more) = dropComment more
    dropComment [] = []
stripComments (c : rest) = c : stripComments rest
stripComments [] = []

-- | Every @OP(a, b, c, d)@ in the text, in file order.
rows :: String -> [Row]
rows text = case breakOn "OP(" text of
  Nothing -> []
  Just after ->
    let (inside, rest) = break (== ')') after
     in case map trim (splitOn ',' inside) of
          [name, token, tag, enc] -> Row (unquote name) token tag enc : rows rest
          _ -> error ("bad OP row: " ++ inside)
  where
    unquote = filter (/= '"')

breakOn :: String -> String -> Maybe String
breakOn pat s
  | pat `isPrefixOf` s = Just (drop (length pat) s)
  | null s = Nothing
  | otherwise = breakOn pat (drop 1 s)

splitOn :: Char -> String -> [String]
splitOn c s = case break (== c) s of
  (a, []) -> [a]
  (a, _ : b) -> a : splitOn c b

trim :: String -> String
trim = reverse . dropWhile isSpace . reverse . dropWhile isSpace

render :: [Row] -> String
render rs =
  unlines $
    [ "-- | GENERATED by tools/GenOpcodes.hs from include/opcodes.h -- do not edit."
    , "--"
    , "-- Regenerate (from port/haskell/):"
    , "--   runghc tools/GenOpcodes.hs ../../include/opcodes.h > src/Opcodes.hs"
    , "--"
    , "-- Every keyword the C engine knows -- instructions, pseudo-instructions"
    , "-- and assembler directives -- in the order of opcodes.h.  The C engine"
    , "-- numbers these tokens from 264 upward in this order (tokens.h); the"
    , "-- numbers appear in the -print-ast output, so 'opcodeToken' keeps them."
    , "module Opcodes"
    , "  ( Opcode (..)"
    , "  , OpRow (..)"
    , "  , opcodeRows"
    , "  , opcodeToken"
    , "  , firstOpcodeToken"
    , "  ) where"
    , ""
    , "import Data.Int (Int32)"
    , "import OpcodeTypes (OpType (..))"
    , ""
    , "-- | One constructor per row of opcodes.h, named like the C token."
    , "data Opcode"
    ]
      ++ zipWith constructor [0 :: Int ..] rs
      ++ [ "  deriving (Eq, Ord, Show, Enum, Bounded)"
         , ""
         , "-- | A row of the table: the mnemonic, its token, its operand shape,"
         , "-- and its binary encoding (-1 for directives and pseudo-ops)."
         , "data OpRow = OpRow"
         , "  { rowName :: String"
         , "  , rowOpcode :: Opcode"
         , "  , rowType :: OpType"
         , "  , rowEncoding :: Int32"
         , "  }"
         , ""
         , "-- | The token number of the first row (tokens.h: 256 + 8 structural tokens)."
         , "firstOpcodeToken :: Int"
         , "firstOpcodeToken = 264"
         , ""
         , "-- | The C engine's integer token for an opcode."
         , "opcodeToken :: Opcode -> Int"
         , "opcodeToken op = firstOpcodeToken + fromEnum op"
         , ""
         , "-- | All rows, in the order of opcodes.h (which is alphabetical)."
         , "opcodeRows :: [OpRow]"
         , "opcodeRows ="
         ]
      ++ zipWith rowLine [0 :: Int ..] rs
      ++ ["  ]"]
  where
    constructor i (Row _ token _ _) = (if i == 0 then "  = " else "  | ") ++ token
    rowLine i (Row name token tag enc) =
      (if i == 0 then "  [ " else "  , ")
        ++ intercalate " " ["OpRow", show name, token, tag, encoding enc]
    -- The C source writes encodings as unsigned hex; as an int32_t they wrap.
    encoding "-1" = "(-1)"
    encoding hex = "(fromIntegral (" ++ hex ++ " :: Integer))"
