/* SPIM S20 MIPS simulator.
   The opcode tables: every instruction, pseudo-instruction, directive
   and REPL command, as the scanner, parser, assembler and disassembler
   look them up (with map_string_to_name_val_val and
   map_int_to_name_val_val, which bsearch them).
   GENERATED by tools/gen_opcodes.py from include/opcodes.tsv -- do not
   edit; change the .tsv and run `make generate`.
   SPDX-License-Identifier: BSD-3-Clause
   See LICENSE in the project root for full text. */

#ifndef OPCODE_TABLES_H
#define OPCODE_TABLES_H

#include "spim-utils.h" /* name_val_val */

/* The number of rows of opcodes.tsv. */
constexpr int OPCODE_COUNT = 365;

/* The number of distinct encodings: the rows of opcode_decode_tbl. */
constexpr int OPCODE_DECODE_COUNT = 276;

/* {name, token, op_type} per row, in opcodes.tsv's order, which is sorted
   both by name (the scanner's keyword search) and by token (a token's
   mnemonic and operand shape). */
extern const name_val_val opcode_tbl[OPCODE_COUNT];

/* {name, token, encoding}: the fixed bits the assembler emits for a
   token, sorted by token. */
extern const name_val_val opcode_encoding_tbl[OPCODE_COUNT];

/* {name, encoding, token}: the token a binary encoding decodes to, one
   row per encoding, sorted by encoding.  Where several rows share an
   encoding, opcodes.tsv's decode column picks the row. */
extern const name_val_val opcode_decode_tbl[OPCODE_DECODE_COUNT];

#endif /* OPCODE_TABLES_H */
